_WORD_RE: Final[re.Pattern[str]] = re.compile(r"[^\W\d_]{3,}", re.UNICODE)


def _estimate_tokens(text: str | None) -> int:
    """Four characters per token — the usual rough rule, stated as a rough rule."""
    if not text:
        return 0
    return max(1, len(text) // 4)


def _salient_terms(text: str, *, limit: int) -> list[str]:
    counts: dict[str, int] = {}
    for word in _WORD_RE.findall(text.lower()):
        counts[word] = counts.get(word, 0) + 1
    ranked = sorted(counts.items(), key=lambda item: (-item[1], item[0]))
    return [word for word, _ in ranked[:limit]]


def _hashed_embedding(text: str, dimensions: int = EMBEDDING_DIMENSIONS) -> list[float]:
    vector = [0.0] * dimensions
    for word in _WORD_RE.findall(text.lower()):
        digest = int(stable_hash("embed", word, length=16), 16)
        index = digest % dimensions
        sign = 1.0 if (digest >> 8) % 2 == 0 else -1.0
        vector[index] += sign
    norm = sum(value * value for value in vector) ** 0.5
    if norm == 0.0:
        return vector
    return [round(value / norm, 8) for value in vector]
