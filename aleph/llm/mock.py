class MockProvider(LLMProvider):
    """A model that answers from a hash of the question.

    Args:
        model: Identifier recorded in responses and in a bundle's methodology.
        seed: Mixed into every derivation, so two mock providers configured
            differently give different — but each internally reproducible —
            answers.
        canned: Exact responses keyed by ``purpose`` or by a substring of the
            prompt. A value may be a JSON-safe object, a string, or a callable
            taking the request. Consulted before synthesis, which is how a test
            pins a specific answer without giving up determinism everywhere else.
        record_calls: Keep every request for later assertion. On by default: the
            call log is how a test checks that the blind evaluator was handed a
            redacted context and nothing more.
    """

    name = "mock"

    def __init__(
        self,
        *,
        model: str = MOCK_MODEL_ID,
        seed: int | str = 20260807,
        temperature: float = 0.0,
        max_tokens: int = DEFAULT_MAX_TOKENS,
        timeout: float = DEFAULT_TIMEOUT_SECONDS,
        canned: Mapping[str, Any] | None = None,
        record_calls: bool = True,
    ) -> None:
        super().__init__(
            model=model,
            temperature=temperature,
            max_tokens=max_tokens,
            timeout=timeout,
            # One attempt: a deterministic provider that failed validation once
            # would fail it identically forever, so retrying is pure latency.
            retry=RetryPolicy(max_attempts=1),
            sleep=lambda _seconds: None,
        )
        self.seed = seed
        self._canned: dict[str, Any] = dict(canned or {})
        self.record_calls = record_calls
        self.calls: list[LLMRequest] = []

    # -- configuration ------------------------------------------------------

    @classmethod
    def from_config(cls, config: Any = None, **overrides: Any) -> MockProvider:
        from aleph.core.config import get_config

        cfg = config or get_config()
        kwargs: dict[str, Any] = {
            "seed": cfg.seed,
            "temperature": cfg.llm_temperature,
        }
        kwargs.update(overrides)
        return cls(**kwargs)

    def register(self, key: str, payload: Any | Callable[[LLMRequest], Any]) -> None:
        """Pin the answer for calls whose ``purpose`` or prompt matches ``key``."""
        self._canned[key] = payload

    def clear_calls(self) -> None:
        self.calls.clear()

    @property
    def call_count(self) -> int:
        return len(self.calls)

    @property
    def is_deterministic(self) -> bool:
        """True, and it is the reason this provider exists."""
        return True

    # -- invocation ---------------------------------------------------------

    def _invoke(self, request: LLMRequest) -> LLMResponse:
        if self.record_calls:
            self.calls.append(request)
        return self._respond(request)

    async def _ainvoke(self, request: LLMRequest) -> LLMResponse:
        """Identical to :meth:`_invoke`; no I/O, so nothing to await.

        Deliberately not routed through a thread: an async caller must get the
        same answer as a sync one, and adding concurrency here would add a way
        for them to differ.
        """
        if self.record_calls:
            self.calls.append(request)
        return self._respond(request)

    def _respond(self, request: LLMRequest) -> LLMResponse:
        fingerprint = request.fingerprint()
        payload = self._canned_for(request)

        if payload is None and request.schema is not None:
            payload = synthesise_from_schema(request.schema, seed=(self.seed, fingerprint))

        if payload is None:
            text = self._prose(request, fingerprint)
        elif isinstance(payload, str):
            text = payload
        else:
            text = json.dumps(payload, ensure_ascii=False, indent=2)

        mode = (
            StructuredOutputMode.JSON_SCHEMA
            if request.schema is not None
            else StructuredOutputMode.NONE
        )
        return LLMResponse(
            text=text,
            model=self.model_id,
            provider=self.name,
            usage=TokenUsage(
                prompt_tokens=_estimate_tokens(request.prompt) + _estimate_tokens(request.system),
                completion_tokens=_estimate_tokens(text),
            ),
            # Derived from the request rather than measured, so that a bundle
            # built offline is byte-identical across runs and machines.
            latency_ms=1.0 + (int(fingerprint[:4], 16) % 500) / 100.0,
            finish_reason=FinishReason.STOP,
            structured_output_mode=mode,
        )

    def _canned_for(self, request: LLMRequest) -> Any | None:
        if not self._canned:
            return None
        candidates: list[Any] = []
        if request.purpose and request.purpose in self._canned:
            candidates.append(self._canned[request.purpose])
        for key, value in self._canned.items():
            if key and key in request.prompt:
                candidates.append(value)
        if not candidates:
            return None
        chosen = candidates[0]
        return chosen(request) if callable(chosen) else chosen

    def _prose(self, request: LLMRequest, fingerprint: str) -> str:
        """Deterministic free text for schema-less calls.

        Echoes salient terms from the prompt so a caller inspecting the output
        can tell which call produced it, and says plainly that it came from the
        offline provider — free text that silently looked like analysis would be
        the easiest way for demonstration content to be mistaken for a result.
        """
        stream = _Stream(self.seed, fingerprint)
        terms = _salient_terms(request.prompt, limit=6)
        subject = ", ".join(terms) if terms else "the supplied input"
        return (
            f"Offline deterministic response (provider={self.name}, "
            f"model={self.model_id}). Concerning {subject}: "
            f"{stream.choice(list(_GENERIC_PHRASES))}."
        )

    # -- embeddings ---------------------------------------------------------

    def embed(self, texts: Sequence[str]) -> list[list[float]]:
        """Hashed bag-of-words vectors, L2-normalised.

        A real, usable implementation rather than a stub: identical texts give
        identical vectors, texts sharing vocabulary sit closer than texts that
        do not, and no network or model is involved. Adequate for clustering and
        near-duplicate detection in an offline run. It carries no semantics
        beyond lexical overlap, and nothing in the factual path may treat it as
        if it did.
        """
        return [_hashed_embedding(text) for text in texts]


