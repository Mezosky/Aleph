def _string_for_pattern(pattern: str, stream: _Stream, min_length: int) -> str:
    """Return a string matching ``pattern``, or raise.

    Tries a table of known-good values first, then a small constructive
    generator for the anchored ``literal + character-class`` shapes the contract
    uses. Every candidate is verified with :func:`re.fullmatch` before it is
    returned, so this function cannot emit a value that violates the constraint.
    """
    compiled = re.compile(pattern)

    ordered = list(_PATTERN_CANDIDATES)
    # Rotate deterministically so repeated fields in one object do not all
    # collapse to the same id.
    offset = stream.below(len(ordered))
    ordered = ordered[offset:] + ordered[:offset]

    for candidate in ordered:
        if _matches(compiled, candidate, min_length):
            return candidate

    constructed = _construct_for_pattern(pattern)
    if constructed is not None:
        for suffix in ("", "1", "a", "-1", "01"):
            candidate = constructed + suffix
            if _matches(compiled, candidate, min_length):
                return candidate

    raise ProviderError(
        "MockProvider cannot synthesise a string for this pattern; register an "
        "explicit canned response for this call",
        provider="mock",
        operation="synthesise",
        retryable=False,
        pattern=pattern,
    )


def _matches(compiled: re.Pattern[str], candidate: str, min_length: int) -> bool:
    if len(candidate) < min_length:
        return False
    anchored = compiled.pattern.startswith("^") and compiled.pattern.endswith("$")
    if anchored:
        return compiled.match(candidate) is not None
    return compiled.search(candidate) is not None


_TOKEN_RE: Final[re.Pattern[str]] = re.compile(
    r"""
    (?P<group>\((?:\?:)?[^()]*\))     # (a|b|c) or (?:a|b|c)
  | (?P<klass>\[[^\]]+\])             # [A-Za-z0-9._-]
  | (?P<escape>\\[dwWsSD.\-/:])       # \d \w \.
  | (?P<literal>[^\\\[\]()*+?{}^$|])  # a plain character
    """,
    re.VERBOSE,
)

# No leading ``^``: this is used with ``match(body, index)``, and ``^`` would
# only ever match at position zero of the whole string.
_QUANT_RE: Final[re.Pattern[str]] = re.compile(r"(?:\{(\d+)(?:,(\d*))?\}|([*+?]))")


def _construct_for_pattern(pattern: str) -> str | None:
    """Build a minimal string for the anchored subset of regex Aleph uses.

    Handles literals, character classes, simple alternation groups and the
    ``* + ? {n} {n,m}`` quantifiers. Returns ``None`` for anything richer rather
    than producing a string that only looks right.
    """
    body = pattern
    if body.startswith("^"):
        body = body[1:]
    if body.endswith("$"):
        body = body[:-1]

    out: list[str] = []
    index = 0
    length = len(body)
    while index < length:
        match = _TOKEN_RE.match(body, index)
        if match is None:
            return None
        index = match.end()
        piece = _sample_token(match)
        if piece is None:
            return None
        repeat = 1
        quant = _QUANT_RE.match(body, index)
        if quant is not None:
            index = quant.end()
            if quant.group(3) == "*" or quant.group(3) == "?":
                repeat = 0 if quant.group(3) == "*" else 1
            elif quant.group(3) == "+":
                repeat = 1
            else:
                repeat = int(quant.group(1))
        out.append(piece * repeat)
    return "".join(out)


def _sample_token(match: re.Match[str]) -> str | None:
    if match.group("literal") is not None:
        return match.group("literal")
    if match.group("escape") is not None:
        return _CLASS_SAMPLE.get(match.group("escape"), "a")
    if match.group("klass") is not None:
        return _sample_class(match.group("klass"))
    group = match.group("group")
    if group is not None:
        inner = group[1:-1]
        if inner.startswith("?:"):
            inner = inner[2:]
        first = inner.split("|")[0]
        return first if first and re.fullmatch(r"[A-Za-z0-9_.\-]+", first) else None
    return None


def _sample_class(klass: str) -> str | None:
    inner = klass[1:-1]
    if inner.startswith("^"):
        return "a"
    ranges = re.findall(r"([A-Za-z0-9])-([A-Za-z0-9])", inner)
    if ranges:
        low, _high = ranges[0]
        return low
    literals = re.sub(r"\\(.)", r"\1", inner)
    return literals[0] if literals else None


def _merge(base: Mapping[str, Any], overlay: Mapping[str, Any]) -> dict[str, Any]:
    out = dict(base)
    for key, value in overlay.items():
        if key == "required":
            out[key] = sorted({*(out.get("required") or []), *value})
        elif key == "properties":
            merged = dict(out.get("properties") or {})
            merged.update(value)
            out[key] = merged
        else:
            out[key] = value
    return out


