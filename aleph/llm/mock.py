def synthesise_from_schema(
    schema: Mapping[str, Any],
    *,
    seed: object = "aleph",
    root: Mapping[str, Any] | None = None,
    documents: Mapping[str, Mapping[str, Any]] | None = None,
) -> Any:
    """Construct a value that validates against ``schema``.

    Deterministic in ``seed``: the same schema and seed always produce the same
    value. Supports the subset of JSON Schema draft 2020-12 that Aleph's own
    contract uses, which is deliberately a subset — a synthesiser that guessed
    at exotic keywords would produce values that *look* valid and are not.

    Args:
        schema: The schema to satisfy.
        seed: Anything hashable-to-string; distinct seeds give distinct values.
        root: The document ``$ref`` pointers resolve against. Defaults to
            ``schema`` itself, which is the usual case.
        documents: Sibling schema documents keyed by the filename a ``$ref``
            uses, e.g. ``{"common.json": {...}}``. Aleph's own contract is split
            across files that cross-reference each other by relative name, so
            without this the shared ``$defs`` — every confidence, every id,
            every enum — would not resolve. An unresolvable ``$ref`` degrades to
            an unconstrained value rather than raising, because a caller may
            legitimately supply only the fragment they care about.

    Returns:
        A JSON-safe Python value.

    Raises:
        ProviderError: A ``pattern`` constraint could not be satisfied. Failing
            loudly is correct: emitting a string that violates the pattern would
            push an invalid value into a bundle under the appearance of success.
    """
    stream = _Stream("synthesise", seed)
    base = dict(root if root is not None else schema)
    if documents:
        base = bundle_schema(base, documents)
        if root is None:
            schema = base
    refs = _Refs(base, documents)
    return _synth(dict(schema), refs, stream, "", 0)


def bundle_schema(
    schema: Mapping[str, Any], documents: Mapping[str, Mapping[str, Any]]
) -> dict[str, Any]:
    """Inline cross-file ``$ref`` targets into one self-contained document.

    Aleph's contract is split across files that reference each other by relative
    name (``common.json#/$defs/confidence``), and a target pulled in that way
    carries *its own* internal references, which resolve against *its* file, not
    against the file that imported it. Resolving those lazily would need a
    resolution scope threaded through every recursive call; inlining once up
    front is simpler and has the same result.

    Each imported target lands in the root's ``$defs`` under a mangled name that
    records where it came from, so a bundled schema stays readable when a
    synthesis failure has to be diagnosed.
    """
    bundled = _deepcopy(schema)
    defs: dict[str, Any] = dict(bundled.get("$defs") or {})
    bundled["$defs"] = defs

    imported: dict[tuple[str, str], str] = {}
    queue: list[tuple[str, str]] = []

    def mangle(document_name: str, pointer: str) -> str:
        slug = re.sub(r"[^A-Za-z0-9]+", "_", document_name).strip("_")
        tail = re.sub(r"[^A-Za-z0-9]+", "_", pointer).strip("_")
        return f"{slug}__{tail}" if tail else slug

    def rewrite(node: Any, current_document: str | None) -> Any:
        """Rewrite every ``$ref`` in ``node`` to a root-local pointer."""
        if isinstance(node, list):
            return [rewrite(item, current_document) for item in node]
        if not isinstance(node, dict):
            return node
        out: dict[str, Any] = {}
        for key, value in node.items():
            if key == "$ref" and isinstance(value, str):
                document_name, _, pointer = value.partition("#")
                target_document = document_name or current_document
                if not target_document:
                    out[key] = value  # already root-local
                    continue
                target_document = target_document.rsplit("/", 1)[-1]
                pointer = pointer or "/"
                name = imported.get((target_document, pointer))
                if name is None:
                    name = mangle(target_document, pointer)
                    imported[(target_document, pointer)] = name
                    queue.append((target_document, pointer))
                out[key] = f"#/$defs/{name}"
            else:
                out[key] = rewrite(value, current_document)
        return out

    bundled = rewrite(bundled, None)
    defs = bundled.setdefault("$defs", {})

    guard = 0
    while queue and guard < 2000:
        guard += 1
        document_name, pointer = queue.pop(0)
        name = imported[(document_name, pointer)]
        if name in defs:
            continue
        document = documents.get(document_name)
        target = _pointer_into(document, pointer) if document is not None else None
        # A ref Aleph cannot resolve becomes an unconstrained schema rather than
        # an error: a caller may legitimately hand over only a fragment.
        defs[name] = rewrite(_deepcopy(target), document_name) if target is not None else {}
    return bundled


def _deepcopy(value: Any) -> Any:
    if isinstance(value, Mapping):
        return {key: _deepcopy(item) for key, item in value.items()}
    if isinstance(value, list):
        return [_deepcopy(item) for item in value]
    return value


def _pointer_into(document: Mapping[str, Any], pointer: str) -> Mapping[str, Any] | None:
    node: Any = document
    for part in pointer.strip("/").split("/"):
        if not part:
            continue
        key = part.replace("~1", "/").replace("~0", "~")
        if not isinstance(node, Mapping) or key not in node:
            return None
        node = node[key]
    return node if isinstance(node, Mapping) else None


class _Refs:
    """Resolves ``$ref`` against the root document and its named siblings."""

    __slots__ = ("root", "documents")

    def __init__(
        self,
        root: Mapping[str, Any],
        documents: Mapping[str, Mapping[str, Any]] | None = None,
    ) -> None:
        self.root = root
        self.documents = dict(documents or {})

    def resolve(self, schema: Mapping[str, Any]) -> dict[str, Any]:
        """Follow ``$ref`` chains, merging any sibling keywords over the target."""
        seen = 0
        current = dict(schema)
        while "$ref" in current and seen < _MAX_DEPTH:
            ref = str(current.pop("$ref"))
            seen += 1
            target = self._lookup(ref)
            if target is None:
                break
            current = _merge(dict(target), current)
        return current

    def _lookup(self, ref: str) -> Mapping[str, Any] | None:
        document_name, _, pointer = ref.partition("#")
        if document_name:
            document = self.documents.get(document_name)
            if document is None:
                # Also accept a bare basename, so "./common.json" and
                # "common.json" behave the same.
                document = self.documents.get(document_name.rsplit("/", 1)[-1])
            if document is None:
                return None
        else:
            document = self.root
        node: Any = document
        for part in pointer.strip("/").split("/"):
            if not part:
                continue
            key = part.replace("~1", "/").replace("~0", "~")
            if not isinstance(node, Mapping) or key not in node:
                return None
            node = node[key]
        return node if isinstance(node, Mapping) else None


def _synth(
    schema: Mapping[str, Any],
    refs: _Refs,
    stream: _Stream,
    field_name: str,
    depth: int,
) -> Any:
    schema = refs.resolve(schema)

    if "const" in schema:
        return schema["const"]
    if "default" in schema and depth > 0:
        return schema["default"]
    enum = schema.get("enum")
    if enum:
        return stream.choice(list(enum))

    if "allOf" in schema:
        merged: dict[str, Any] = {}
        for part in schema["allOf"]:
            merged = _merge(merged, refs.resolve(part))
        merged = _merge(merged, {k: v for k, v in schema.items() if k != "allOf"})
        return _synth(merged, refs, stream, field_name, depth)

    for combinator in ("oneOf", "anyOf"):
        options = schema.get(combinator)
        if options:
            branch = _pick_branch(options, refs, stream, depth)
            return _synth(branch, refs, stream, field_name, depth)

    declared = schema.get("type")
    types = [declared] if isinstance(declared, str) else list(declared or [])
    if not types:
        types = ["object" if "properties" in schema else "string"]

    # A nullable field at the depth limit becomes null; that is how a recursive
    # schema terminates without inventing another level of structure.
    if depth >= _MAX_DEPTH and "null" in types:
        return None
    chosen = next((t for t in types if t != "null"), "null")

    if chosen == "object":
        return _synth_object(schema, refs, stream, depth)
    if chosen == "array":
        return _synth_array(schema, refs, stream, field_name, depth)
    if chosen == "string":
        return _synth_string(schema, stream, field_name)
    if chosen == "integer":
        return _synth_integer(schema, stream)
    if chosen == "number":
        return _synth_number(schema, stream)
    if chosen == "boolean":
        return stream.below(2) == 1
    return None


def _pick_branch(
    options: Sequence[Mapping[str, Any]],
    refs: _Refs,
    stream: _Stream,
    depth: int,
) -> Mapping[str, Any]:
    """Choose a branch of ``oneOf``/``anyOf``.

    Non-null branches are preferred until the depth limit, where null is
    preferred: that is what stops a self-referential schema from recursing while
    still producing a populated value at shallow depths.
    """
    resolved = [refs.resolve(opt) for opt in options]
    nulls = [opt for opt in resolved if opt.get("type") == "null"]
    others = [opt for opt in resolved if opt.get("type") != "null"]
    if depth >= _MAX_DEPTH and nulls:
        return nulls[0]
    if others:
        return others[stream.below(len(others))]
    return resolved[0]


def _synth_object(
    schema: Mapping[str, Any], refs: _Refs, stream: _Stream, depth: int
) -> dict[str, Any]:
    properties: Mapping[str, Any] = schema.get("properties") or {}
    required = list(schema.get("required") or [])
    out: dict[str, Any] = {}

    # Required properties always; optional ones deterministically about half the
    # time, so a mock run exercises both the present and absent branches of
    # downstream code rather than only the fullest possible object.
    for name, sub in properties.items():
        include = name in required or stream.below(2) == 1 or depth == 0
        if not include:
            continue
        out[name] = _synth(sub, refs, stream, name, depth + 1)

    for name in required:
        if name not in out:
            sub = properties.get(name, {"type": "string"})
            out[name] = _synth(sub, refs, stream, name, depth + 1)

    min_props = int(schema.get("minProperties", 0) or 0)
    additional = schema.get("additionalProperties", True)
    if len(out) < min_props and additional is not False:
        sub_schema = additional if isinstance(additional, Mapping) else {"type": "string"}
        while len(out) < min_props:
            key = f"key_{len(out)}"
            out[key] = _synth(sub_schema, refs, stream, key, depth + 1)
    return out


def _synth_array(
    schema: Mapping[str, Any],
    refs: _Refs,
    stream: _Stream,
    field_name: str,
    depth: int,
) -> list[Any]:
    items = schema.get("items")
    min_items = int(schema.get("minItems", 0) or 0)
    max_items_raw = schema.get("maxItems")
    max_items = int(max_items_raw) if max_items_raw is not None else None

    if items is None:
        return []
    count = max(min_items, 1)
    if depth >= _MAX_DEPTH:
        count = min_items
    if max_items is not None:
        count = min(count, max_items)
    return [_synth(items, refs, stream, field_name, depth + 1) for _ in range(count)]


def _synth_integer(schema: Mapping[str, Any], stream: _Stream) -> int:
    low = schema.get("minimum")
    high = schema.get("maximum")
    if low is None and schema.get("exclusiveMinimum") is not None:
        low = float(schema["exclusiveMinimum"]) + 1
    if high is None and schema.get("exclusiveMaximum") is not None:
        high = float(schema["exclusiveMaximum"]) - 1
    lo = int(low) if low is not None else 0
    hi = int(high) if high is not None else lo + 10
    if hi < lo:
        hi = lo
    return stream.int_between(lo, hi)


def _synth_number(schema: Mapping[str, Any], stream: _Stream) -> float:
    low = schema.get("minimum", schema.get("exclusiveMinimum", 0.0))
    high = schema.get("maximum", schema.get("exclusiveMaximum", None))
    lo = float(low if low is not None else 0.0)
    hi = float(high if high is not None else lo + 100.0)
    if hi < lo:
        hi = lo
    return stream.between(lo, hi)


def _synth_string(schema: Mapping[str, Any], stream: _Stream, field_name: str) -> str:
    pattern = schema.get("pattern")
    fmt = schema.get("format")
    min_length = int(schema.get("minLength", 0) or 0)
    max_length_raw = schema.get("maxLength")
    max_length = int(max_length_raw) if max_length_raw is not None else None

    if pattern:
        value = _string_for_pattern(str(pattern), stream, min_length)
        return value

    if fmt:
        value = _string_for_format(str(fmt), stream)
        if value is not None:
            return value

    body = _phrase_for(field_name, stream)
    while len(body) < min_length:
        body = f"{body}; {_phrase_for(field_name, stream)}"
    if max_length is not None and len(body) > max_length:
        body = body[:max_length].rstrip()
    return body


def _string_for_format(fmt: str, stream: _Stream) -> str | None:
    if fmt == "date-time":
        return _ANCHOR_TIMESTAMP
    if fmt == "date":
        return _ANCHOR_DATE
    if fmt == "uri" or fmt == "uri-reference":
        return f"https://example.invalid/aleph/mock/{stream.below(9999)}"
    if fmt == "email":
        return "mock@example.invalid"
    if fmt == "duration":
        return "P1D"
    return None


def _phrase_for(field_name: str, stream: _Stream) -> str:
    options = _FIELD_PHRASES.get(field_name)
    if not options:
        for key, phrases in _FIELD_PHRASES.items():
            if phrases and key and key in field_name:
                options = phrases
                break
    return str(stream.choice(list(options or _GENERIC_PHRASES)))


