class _Stream:
    """A counter-driven hash stream. Reproducible, stateless across processes.

    Not a PRNG: every draw is ``hash(seed, counter)``, so two runs with the same
    seed produce the same sequence regardless of platform, Python build or the
    order other components happened to draw in.
    """

    __slots__ = ("_seed", "_counter")

    def __init__(self, *seed_parts: object) -> None:
        self._seed = stable_hash(*seed_parts, length=32)
        self._counter = 0

    def _draw(self) -> int:
        self._counter += 1
        return int(stable_hash(self._seed, self._counter, length=16), 16)

    def below(self, n: int) -> int:
        """A value in ``[0, n)``."""
        return self._draw() % max(1, n)

    def unit(self) -> float:
        """A value in ``[0, 1)``, rounded to 6 places so it serialises cleanly."""
        return round((self._draw() % 1_000_000) / 1_000_000, 6)

    def choice(self, items: Sequence[Any]) -> Any:
        if not items:
            raise ValueError("cannot choose from an empty sequence")
        return items[self.below(len(items))]

    def between(self, low: float, high: float) -> float:
        if high <= low:
            return low
        return round(low + (high - low) * self.unit(), 6)

    def int_between(self, low: int, high: int) -> int:
        if high <= low:
            return low
        return low + self.below(high - low + 1)


