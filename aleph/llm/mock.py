"""A deterministic, offline model provider — the default, and load-bearing.

Most projects treat a mock model as scaffolding for unit tests. In Aleph it is a
first-class component with three jobs that matter to the product itself:

1. **The whole pipeline must run with no credentials.** A tool that audits
   public-policy evidence should be reproducible by anyone who clones it,
   including a reviewer who does not have — and should not need — an inference
   budget in order to check what the code does.
2. **CI must be able to fail.** Tests that depend on a hosted model are tests
   whose failures are ambiguous. Every check in this repository runs against
   this provider, so a red build means Aleph changed, not that a vendor did.
3. **Determinism is an epistemic property, not a convenience.** Two analyses of
   the same document must be diffable. When they differ, the difference has to
   be attributable to the document or to Aleph, never to sampling noise, and
   this provider makes that guarantee absolute for every offline run.

There is no randomness anywhere in this module — not seeded ``random``, not
``uuid``, not wall-clock time. Every value is derived by hashing the request, so
the same :class:`~aleph.llm.base.LLMRequest` produces byte-identical output on
any machine, in any process, in any order.

The core of it is a **schema-driven synthesiser**: given the JSON Schema a caller
asked for, it constructs a value that validates against it — honouring ``$ref``,
``$defs``, ``enum``, ``const``, ``required``, ``additionalProperties: false``,
numeric bounds, array cardinality, string length, ``format`` and ``pattern``.
That is what makes it useful beyond a fixture: any downstream module can pass
its real schema and get back a real, valid object, so the module can be built
and exercised end to end before a single token is ever generated by a real model.

What this provider does **not** do is judge anything. Its output is structurally
valid and semantically arbitrary. A bundle produced with it is demonstration
data and must carry ``data_status: "synthetic"``, which is exactly why that field
is required by the contract rather than optional.
"""

