"""The shared contract every other Aleph package is written against.

Five modules, in dependency order:

* :mod:`aleph.core.enums` — the closed controlled vocabularies. Fixing the set of
  possible verdicts, tiers, axes and dimensions *before* any particular judgement
  is made is what stops a result from being reshaped to fit a conclusion.
* :mod:`aleph.core.ids` — deterministic, human-readable identifiers, so two runs
  over the same document produce a diffable bundle and a cited provision still
  resolves after a refresh.
* :mod:`aleph.core.models` — pydantic mirrors of every JSON Schema, including
  :class:`~aleph.core.models.RedactedClaimContext`, which makes speaker-blindness
  a property of the type system rather than a coding convention.
* :mod:`aleph.core.errors` — the failures Aleph admits to, typed by what a caller
  can do about them, so a source that could not be read becomes a published gap
  instead of a silent absence.
* :mod:`aleph.core.config` — frozen runtime settings whose defaults are the
  cautious ones: deterministic mock model, no network, fixed seed.

Everything here is import-cheap and side-effect free: no I/O beyond reading
``os.environ``, and no network access at import time.
"""

